"""
Track and compare training runs written by train.py (runs/<id>/config.json + summary.json + metrics.jsonl).

    python runs.py                         # table of all runs: status, WERs, notes + every config key that differs
    python runs.py -f lr                   # only runs whose id contains "lr"
    python runs.py --keys LR STACK         # always show these config columns
    python runs.py --sort test-clean       # sort by a column (status, best_val, test-clean, ..., or a config key)
    python runs.py show <run>              # full config + summary of one run
    python runs.py diff <run_a> <run_b>    # config keys that differ between two runs
    python runs.py curve <run> [--every N] # val WER / train loss over steps from metrics.jsonl
    python runs.py plot [<run> ...]        # (re)write runs/<id>/plots.png (default: every run) + runs/INDEX.md
    python runs.py latest                  # path of the newest run (also always at runs/latest/)

<run> can be a path (runs/2026...), a run id, any unique substring of a run id, or "latest".
train.py keeps runs/latest -> newest run dir, runs/INDEX.md (all runs, newest first) and runs/<id>/plots.png up to date.
"""
import argparse
import json
import re
import sys
import time
from pathlib import Path

import numpy as np

RUNS_DIR = Path("runs")
# Config keys that are bookkeeping rather than hyperparameters; never shown as "differing" columns.
IGNORED_KEYS = {"RUN_NAME", "NUM_WORKERS", "LOG_EVERY", "LOG_N_EXAMPLES", "DEVICE", "EVAL_BATCH_SIZE", "PLOT_EVERY",
                "BENCHMARK_SETS", "ASR_CORPORA", "EVAL_AUDIO_ABLATIONS"}


def load_run(run_dir):
    """Return {"id", "dir", "config", "meta", "summary"} for a run directory, tolerating older runs."""
    config = json.load(open(run_dir / "config.json"))
    meta = config.pop("meta", {})
    for legacy_key in ("git", "max_steps"):  # flat metadata written by older train.py versions
        if legacy_key in config:
            meta.setdefault(legacy_key, config.pop(legacy_key))
    summary_path, test_path = run_dir / "summary.json", run_dir / "test_results.json"
    summary = json.load(open(summary_path)) if summary_path.exists() else {}
    if "test_wer" not in summary and test_path.exists():
        summary["test_wer"] = {k: round(v["wer"] * 100, 2) for k, v in json.load(open(test_path)).items()}
    log_path = run_dir / "log.txt"
    if "best_val_wer" not in summary and log_path.exists():  # older runs: recover it from the final log line
        done = re.findall(r"training done: (\d+) steps.*best val WER ([\d.]+) @ step (\d+)", log_path.read_text())
        if done:
            steps, wer, step = done[-1]
            summary.update(best_val_wer=float(wer), best_val_step=int(step), step=int(steps), total_steps=int(steps))
            summary.setdefault("status", "done")
    summary.setdefault("status", "unknown")
    return {"id": run_dir.name, "dir": run_dir, "config": config, "meta": meta, "summary": summary}


def all_runs():
    """Every run dir, oldest first (by start time; legacy runs without it by config.json mtime). Skips runs/latest."""
    runs = [load_run(p.parent) for p in RUNS_DIR.glob("*/config.json") if not p.parent.is_symlink()]
    start = lambda run: run["meta"].get("started_at") or time.strftime(
        "%Y-%m-%d %H:%M:%S", time.localtime((run["dir"] / "config.json").stat().st_mtime))
    return sorted(runs, key=lambda run: (start(run), run["id"]))


def latest_run_dir():
    """The most recently started run (same order as all_runs, so it also works without the symlink)."""
    runs = all_runs()
    return runs[-1]["dir"] if runs else None


def update_latest_link(run_dir):
    """Point runs/latest -> <run_dir> (relative symlink), so the newest run is always at runs/latest/."""
    link = RUNS_DIR / "latest"
    tmp = RUNS_DIR / ".latest.tmp"
    tmp.unlink(missing_ok=True)
    tmp.symlink_to(Path(run_dir).name)
    tmp.replace(link)  # atomic swap


def write_index():
    """runs/INDEX.md: one line per run, newest first, with what it changed and how it did. Rewritten by train.py."""
    runs = all_runs()[::-1]
    lines = ["# Runs (newest first; regenerated by train.py, `python runs.py` for the full table)", "",
             "| run | status | model | changed vs defaults | best val WER | test-clean / other | benchmark avg | notes |",
             "|---|---|---|---|---|---|---|---|"]
    for run in runs:
        summary, overrides = run["summary"], run["meta"].get("overrides", {})
        changed = ", ".join(f"{k.lower()}={fmt(v)}" for k, v in overrides.items() if k not in IGNORED_KEYS) or "-"
        test = summary.get("test_wer", {})
        bench = summary.get("benchmark", {})
        bench_avg = f"{sum(bench.values()) / len(bench):.2f} ({len(bench)} sets)" if bench else "-"
        step = f" {summary['step']}/{summary['total_steps']}" if summary["status"] == "running" and "step" in summary else ""
        lines.append(
            f"| [{run['id']}]({run['id']}/) | {summary['status']}{step} | {run['config'].get('MODEL', '?').split('/')[-1]} "
            f"| {changed} | {fmt(summary.get('best_val_wer'))} | {fmt(test.get('test-clean'))} / {fmt(test.get('test-other'))} "
            f"| {bench_avg} | {run['meta'].get('notes') or summary.get('notes') or ''} |"
        )
    (RUNS_DIR / "INDEX.md").write_text("\n".join(lines) + "\n")


def refresh_run_views(run_dir, log=None):
    """Re-plot runs/<id>/plots.png and rewrite runs/INDEX.md. Never raises: a plotting bug must not kill training."""
    try:
        plot_run(run_dir)
        write_index()
    except Exception as error:  # noqa: BLE001
        (log or print)(f"warning: could not refresh plots/index for {run_dir}: {error!r}")


def plot_run(run_dir):
    """
    Write <run_dir>/plots.png from metrics.jsonl + summary.json: train loss, grad norm (+ clip threshold), lr,
    val WER (+ sub/del/ins, test WER), throughput and memory. Returns the path, or None if there is nothing to plot.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    run = load_run(Path(run_dir))
    metrics_path = run["dir"] / "metrics.jsonl"
    if not metrics_path.exists():
        return None
    rows = [json.loads(line) for line in open(metrics_path) if line.strip()]
    train = [r for r in rows if r["type"] == "train"]
    val = [r for r in rows if r["type"] == "val"]
    if not train and not val:
        return None
    summary, cfg = run["summary"], run["config"]
    col = lambda rs, key: [r.get(key) for r in rs]
    steps = col(train, "step")

    fig, axes = plt.subplots(2, 3, figsize=(17, 9))
    (ax_loss, ax_gnorm, ax_lr), (ax_val, ax_speed, ax_mem) = axes

    if train:
        loss = col(train, "loss")
        ema, smoothed = None, []
        for value in loss:
            ema = value if ema is None else 0.9 * ema + 0.1 * value
            smoothed.append(ema)
        ax_loss.plot(steps, loss, alpha=0.35, label="loss (per log window)")
        ax_loss.plot(steps, smoothed, label="EMA 0.9")
        ax_loss.set_title(f"train loss (last {loss[-1]:.3f}, min {min(loss):.3f})")
        ax_loss.legend()

        ax_gnorm.plot(steps, col(train, "grad_norm_avg"), label="avg (pre-clip)")
        ax_gnorm.plot(steps, col(train, "grad_norm_max"), alpha=0.5, label="max (pre-clip)")
        if train[0].get("lora_grad_norm_avg") is not None:
            ax_gnorm.plot(steps, col(train, "lora_grad_norm_avg"), "--", alpha=0.8, label="lora avg")
            ax_gnorm.plot(steps, col(train, "proj_grad_norm_avg"), "--", alpha=0.8, label="proj avg")
        if cfg.get("GRAD_CLIP"):
            ax_gnorm.axhline(cfg["GRAD_CLIP"], color="red", ls="--", lw=1, label=f"clip {cfg['GRAD_CLIP']}")
        clipped = sum(col(train, "clipped"))
        n_steps = len(train) * cfg.get("LOG_EVERY", 1)
        ax_gnorm.set_yscale("log")
        ax_gnorm.set_title(f"grad norm ({clipped}/{n_steps} steps clipped = {clipped / max(1, n_steps):.0%})")
        ax_gnorm.legend()

        ax_lr.plot(steps, col(train, "lr"))
        ax_lr.set_title(f"learning rate (peak {cfg.get('LR')}, warmup {cfg.get('WARMUP_STEPS')})")
        ax_lr.ticklabel_format(axis="y", style="sci", scilimits=(0, 0))

        ax_speed.plot(steps, col(train, "tok_per_sec"), label="tok/s")
        ax_speed.set_title(f"throughput (median {np.median(col(train, 'sec_per_step')):.2f} s/step)")
        ax_speed.legend(loc="lower left")
        ax_mem.plot(steps, col(train, "peak_mem_gb"))
        ax_mem.set_title("peak GPU memory allocated (GB)")

    if val:
        val_steps = col(val, "step")
        ax_val.plot(val_steps, [100 * w for w in col(val, "wer")], "o-", lw=2, label="WER")
        for key in ("sub", "del", "ins"):
            if val[0].get(key) is not None:
                ax_val.plot(val_steps, [100 * v for v in col(val, key)], ".--", alpha=0.7, label=key)
        for key in ("wer_shuffle", "wer_zeros"):
            if val[0].get(key) is not None:
                ax_val.plot(val_steps, [100 * v for v in col(val, key)], "x:", alpha=0.8, label=key)
        if summary.get("best_val_step") is not None:
            ax_val.axvline(summary["best_val_step"], color="gray", ls=":", lw=1, label=f"best @ {summary['best_val_step']}")
        for split, wer in summary.get("test_wer", {}).items():
            ax_val.scatter([val_steps[-1]], [wer], marker="*", s=120, zorder=5, label=f"test {split} {wer:.2f}")
        ax_val.set_title(f"val WER % on {cfg.get('VAL_SPLIT')}[:{cfg.get('VAL_N')}] (best {fmt(summary.get('best_val_wer'))})")
        ax_val.legend(fontsize=8)

    for ax in axes.flat:
        ax.set_xlabel("optimizer step")
        ax.grid(alpha=0.3)
    bench = {**summary.get("benchmark", {}), **summary.get("benchmark_extra", {})}
    bench_text = ("  |  benchmark: " + ", ".join(f"{k} {v:.2f}" for k, v in bench.items())) if bench else ""
    overrides = {k: v for k, v in run["meta"].get("overrides", {}).items() if k not in IGNORED_KEYS}
    fig.suptitle(f"{run['id']}  [{summary['status']}"
                 + (f" {summary['step']}/{summary['total_steps']}" if "step" in summary else "") + "]\n"
                 + f"{cfg.get('MODEL')} | overrides: {', '.join(f'{k}={fmt(v)}' for k, v in overrides.items()) or 'none'}"
                 + bench_text, fontsize=10)
    fig.tight_layout()
    out = run["dir"] / "plots.png"
    fig.savefig(out, dpi=90)
    plt.close(fig)
    return out


def is_candidate(run):
    """A finished full-length run with a saved checkpoint and a dev val WER (no smoke/subset/train-overfit runs)."""
    cfg = run["config"]
    return ((run["dir"] / "proj.pt").exists() and not run["meta"].get("max_steps")
            and not cfg.get("VAL_FROM_TRAIN") and not cfg.get("TRAIN_N")
            and run["summary"]["status"] == "done" and run["summary"].get("best_val_wer") is not None)


def model_size(model_id):
    """Parameter count parsed from a model id, for sorting: "LiquidAI/LFM2.5-1.2B-Base" -> 1.2e9."""
    match = re.search(r"(\d+(?:\.\d+)?)([MB])\b", model_id.split("/")[-1])
    return float(match[1]) * (1e6 if match[2] == "M" else 1e9) if match else float("inf")


def best_runs_by_model(runs=None):
    """
    One best run per base LLM (config MODEL): the candidate with the lowest best_val_wer (in-training dev WER), so the
    test sets are never used for selection. Returns {MODEL: (best_run, n_candidates)}, smallest LLM first.
    """
    groups = {}
    for run in runs if runs is not None else all_runs():
        if is_candidate(run):
            groups.setdefault(run["config"].get("MODEL", "?"), []).append(run)
    return {
        model: (min(group, key=lambda run: run["summary"]["best_val_wer"]), len(group))
        for model, group in sorted(groups.items(), key=lambda item: (model_size(item[0]), item[0]))
    }


def resolve_run(name):
    if name == "latest":
        latest = latest_run_dir()
        if latest is None:
            sys.exit(f"no runs in {RUNS_DIR}/")
        return load_run(latest)
    path = Path(name)
    if (path / "config.json").exists():
        return load_run(path)
    matches = [run for run in all_runs() if name in run["id"]]
    exact = [run for run in matches if run["id"] == name] or [run for run in matches if run["id"].endswith("_" + name)]
    if exact or len(matches) == 1:
        return (exact or matches)[0]
    sys.exit(f"no unique run matching {name!r}: {[run['id'] for run in matches] or 'none'}")


def fmt(val):
    if val is None:
        return "-"
    if isinstance(val, float):
        return f"{val:.3g}" if abs(val) < 1e-2 or abs(val) >= 1e4 else f"{val:g}"
    if isinstance(val, list):
        return ",".join(map(str, val))
    return str(val)


def print_table(header, rows):
    widths = [max(len(str(cell)) for cell in column) for column in zip(header, *rows)]
    line = lambda cells: "  ".join(str(cell).ljust(width) for cell, width in zip(cells, widths)).rstrip()
    print(line(header))
    print(line("-" * width for width in widths))
    for row in rows:
        print(line(row))


def cmd_list(args):
    runs = [run for run in all_runs() if not args.filter or args.filter in run["id"]]
    if not runs:
        sys.exit(f"no runs found in {RUNS_DIR}/")

    test_splits = sorted({split for run in runs for split in run["summary"].get("test_wer", {})})
    all_keys = sorted({key for run in runs for key in run["config"]} - IGNORED_KEYS)
    differing = [key for key in all_keys if len({json.dumps(run["config"].get(key)) for run in runs}) > 1]
    config_keys = list(dict.fromkeys((args.keys or []) + differing))

    header = ["run", "status", "step", "best_val", *test_splits, *config_keys, "notes"]
    rows = []
    latest = latest_run_dir()
    for run in runs:
        summary = run["summary"]
        step = f"{summary['step']}/{summary['total_steps']}" if "step" in summary else "-"
        rows.append([
            run["id"] + (" <- latest" if run["dir"] == latest else ""), summary["status"] + ("*" if run["meta"].get("git_dirty") else ""), step,
            fmt(summary.get("best_val_wer")),
            *[fmt(summary.get("test_wer", {}).get(split)) for split in test_splits],
            *[fmt(run["config"].get(key)) for key in config_keys],
            (run["meta"].get("notes") or summary.get("notes") or "")[:40],
        ])
    if args.sort:
        column = header.index(args.sort) if args.sort in header else None
        if column is None:
            sys.exit(f"--sort must be one of {header}")
        as_number = lambda cell: (0, float(cell)) if cell.replace(".", "", 1).isdigit() else (1, cell)
        rows.sort(key=lambda row: as_number(row[column]))
    print_table(header, rows)
    print("\n* = launched from a dirty git tree (see runs/<id>/git_diff.patch). WER in %.")
    if not differing:
        print("all runs share the same config (use --keys to show columns anyway)")


def cmd_show(args):
    run = resolve_run(args.run)
    print(f"# {run['id']}  ({run['dir']})")
    print("\n## summary")
    print(json.dumps(run["summary"], indent=2))
    print("\n## meta")
    print(json.dumps(run["meta"], indent=2))
    print("\n## config")
    print_table(["key", "value"], [[key, fmt(val)] for key, val in run["config"].items()])


def cmd_diff(args):
    run_a, run_b = resolve_run(args.run_a), resolve_run(args.run_b)
    keys = sorted(set(run_a["config"]) | set(run_b["config"]))
    rows = [
        [key, fmt(run_a["config"].get(key)), fmt(run_b["config"].get(key))]
        for key in keys if run_a["config"].get(key) != run_b["config"].get(key)
    ]
    for label, extract in [("best_val_wer", lambda s: s.get("best_val_wer")), ("status", lambda s: s["status"])]:
        rows.append([f"[{label}]", fmt(extract(run_a["summary"])), fmt(extract(run_b["summary"]))])
    for split in sorted(set(run_a["summary"].get("test_wer", {})) | set(run_b["summary"].get("test_wer", {}))):
        rows.append([f"[test {split}]", fmt(run_a["summary"].get("test_wer", {}).get(split)),
                     fmt(run_b["summary"].get("test_wer", {}).get(split))])
    print_table(["key", run_a["id"], run_b["id"]], rows)


def cmd_curve(args):
    run = resolve_run(args.run)
    metrics_path = run["dir"] / "metrics.jsonl"
    if not metrics_path.exists():
        sys.exit(f"{metrics_path} not found (run predates metrics tracking)")
    rows = [json.loads(line) for line in open(metrics_path)]
    train_rows = [r for r in rows if r["type"] == "train"][:: args.every]
    print_table(["step", "loss", "lr", "gnorm_avg", "s/step"],
                [[r["step"], f"{r['loss']:.4f}", f"{r['lr']:.2e}", f"{r['grad_norm_avg']:.2f}",
                  f"{r['sec_per_step']:.2f}"] for r in train_rows])
    val_rows = [r for r in rows if r["type"] == "val"]
    if val_rows:
        print()
        print_table(["step", "val WER", "sub", "del", "ins"],
                    [[r["step"], *(f"{r[k] * 100:.2f}" for k in ("wer", "sub", "del", "ins"))] for r in val_rows])


def cmd_plot(args):
    runs = [resolve_run(name) for name in args.runs] if args.runs else all_runs()
    for run in runs:
        print(plot_run(run["dir"]) or f"{run['id']}: no metrics.jsonl, nothing to plot")
    write_index()
    print(RUNS_DIR / "INDEX.md")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-f", "--filter", help="only runs whose id contains this substring")
    parser.add_argument("--keys", nargs="+", help="config keys to always show as columns (e.g. LR STACK)")
    parser.add_argument("--sort", help="column to sort by")
    sub = parser.add_subparsers(dest="cmd")
    show = sub.add_parser("show", help="full config + summary of one run")
    show.add_argument("run")
    diff = sub.add_parser("diff", help="config differences between two runs")
    diff.add_argument("run_a")
    diff.add_argument("run_b")
    curve = sub.add_parser("curve", help="train loss / val WER over steps")
    curve.add_argument("run")
    curve.add_argument("--every", type=int, default=1, help="print every Nth train row")
    plot = sub.add_parser("plot", help="write runs/<id>/plots.png (default: all runs) and runs/INDEX.md")
    plot.add_argument("runs", nargs="*")
    sub.add_parser("latest", help="print the newest run dir")
    args = parser.parse_args()
    {"show": cmd_show, "diff": cmd_diff, "curve": cmd_curve, "plot": cmd_plot,
     "latest": lambda _: print(latest_run_dir())}.get(args.cmd, cmd_list)(args)


if __name__ == "__main__":
    main()
